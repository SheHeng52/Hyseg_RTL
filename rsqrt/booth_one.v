`timescale 1ns / 1ps

module booth_one (
    input      [9:0]   k,
    input      [18:0]  x,
    output reg [132:0] pd,
    output reg [5:0]   neg
);

    // x = 19 bit
    // 扩展后为 21 bit
    wire [20:0] x1;
    wire [20:0] xn1;
    wire [20:0] x2;
    wire [20:0] xn2;

    assign x1  = {2'b00, x};        // +x
    assign xn1 = ~x1;               // ~x

    assign x2  = {1'b0, x, 1'b0};  // +2x
    assign xn2 = ~x2;               // ~2x


    always @* begin

        // ========================================================
        // group 0
        // Booth code = k[1:0]
        //
        // pp0 = 23 bit
        // pd[22:0]
        // ========================================================

        case (k[1:0])

            2'b00: begin
                pd[22:0] = {
                    1'b1,
                    1'b0,
                    1'b0,
                    20'b0
                };
                neg[0] = 1'b0;
            end

            2'b01: begin
                pd[22:0] = {
                    ~x1[20],
                    x1[20],
                    x1[20],
                    x1[19:0]
                };
                neg[0] = 1'b0;
            end

            2'b10: begin
                pd[22:0] = {
                    ~xn2[20],
                    xn2[20],
                    xn2[20],
                    xn2[19:0]
                };
                neg[0] = 1'b1;
            end

            2'b11: begin
                pd[22:0] = {
                    ~xn1[20],
                    xn1[20],
                    xn1[20],
                    xn1[19:0]
                };
                neg[0] = 1'b1;
            end

            default: begin
                pd[22:0] = 23'b0;
                neg[0]   = 1'b0;
            end

        endcase


        // ========================================================
        // group 1
        // Booth code = k[3:1]
        //
        // pp1 = 22 bit
        // pd[44:23]
        // ========================================================

        case (k[3:1])

            3'b000: begin
                pd[44:23] = {1'b1, 1'b1, 20'b0};
                neg[1]    = 1'b0;
            end

            3'b001,
            3'b010: begin
                pd[44:23] = {1'b1, ~x1[20], x1[19:0]};
                neg[1]    = 1'b0;
            end

            3'b011: begin
                pd[44:23] = {1'b1, ~x2[20], x2[19:0]};
                neg[1]    = 1'b0;
            end

            3'b100: begin
                pd[44:23] = {1'b1, ~xn2[20], xn2[19:0]};
                neg[1]    = 1'b1;
            end

            3'b101,
            3'b110: begin
                pd[44:23] = {1'b1, ~xn1[20], xn1[19:0]};
                neg[1]    = 1'b1;
            end

            3'b111: begin
                pd[44:23] = {1'b1, 1'b1, 20'b0};
                neg[1]    = 1'b0;
            end

            default: begin
                pd[44:23] = 22'b0;
                neg[1]    = 1'b0;
            end

        endcase


        // ========================================================
        // group 2
        // Booth code = k[5:3]
        // pd[66:45]
        // ========================================================

        case (k[5:3])

            3'b000: begin
                pd[66:45] = {1'b1, 1'b1, 20'b0};
                neg[2]    = 1'b0;
            end

            3'b001,
            3'b010: begin
                pd[66:45] = {1'b1, ~x1[20], x1[19:0]};
                neg[2]    = 1'b0;
            end

            3'b011: begin
                pd[66:45] = {1'b1, ~x2[20], x2[19:0]};
                neg[2]    = 1'b0;
            end

            3'b100: begin
                pd[66:45] = {1'b1, ~xn2[20], xn2[19:0]};
                neg[2]    = 1'b1;
            end

            3'b101,
            3'b110: begin
                pd[66:45] = {1'b1, ~xn1[20], xn1[19:0]};
                neg[2]    = 1'b1;
            end

            3'b111: begin
                pd[66:45] = {1'b1, 1'b1, 20'b0};
                neg[2]    = 1'b0;
            end

            default: begin
                pd[66:45] = 22'b0;
                neg[2]    = 1'b0;
            end

        endcase


        // ========================================================
        // group 3
        // Booth code = k[7:5]
        // pd[88:67]
        // ========================================================

        case (k[7:5])

            3'b000: begin
                pd[88:67] = {1'b1, 1'b1, 20'b0};
                neg[3]    = 1'b0;
            end

            3'b001,
            3'b010: begin
                pd[88:67] = {1'b1, ~x1[20], x1[19:0]};
                neg[3]    = 1'b0;
            end

            3'b011: begin
                pd[88:67] = {1'b1, ~x2[20], x2[19:0]};
                neg[3]    = 1'b0;
            end

            3'b100: begin
                pd[88:67] = {1'b1, ~xn2[20], xn2[19:0]};
                neg[3]    = 1'b1;
            end

            3'b101,
            3'b110: begin
                pd[88:67] = {1'b1, ~xn1[20], xn1[19:0]};
                neg[3]    = 1'b1;
            end

            3'b111: begin
                pd[88:67] = {1'b1, 1'b1, 20'b0};
                neg[3]    = 1'b0;
            end

            default: begin
                pd[88:67] = 22'b0;
                neg[3]    = 1'b0;
            end

        endcase


        // ========================================================
        // group 4
        // Booth code = k[9:7]
        // pd[110:89]
        // ========================================================

        case (k[9:7])

            3'b000: begin
                pd[110:89] = {1'b1, 1'b1, 20'b0};
                neg[4]     = 1'b0;
            end

            3'b001,
            3'b010: begin
                pd[110:89] = {1'b1, ~x1[20], x1[19:0]};
                neg[4]     = 1'b0;
            end

            3'b011: begin
                pd[110:89] = {1'b1, ~x2[20], x2[19:0]};
                neg[4]     = 1'b0;
            end

            3'b100: begin
                pd[110:89] = {1'b1, ~xn2[20], xn2[19:0]};
                neg[4]     = 1'b1;
            end

            3'b101,
            3'b110: begin
                pd[110:89] = {1'b1, ~xn1[20], xn1[19:0]};
                neg[4]     = 1'b1;
            end

            3'b111: begin
                pd[110:89] = {1'b1, 1'b1, 20'b0};
                neg[4]     = 1'b0;
            end

            default: begin
                pd[110:89] = 22'b0;
                neg[4]     = 1'b0;
            end

        endcase


        // ========================================================
        // group 5
        //
        // k为10-bit unsigned
        // 标准 Booth group：
        //
        // {k[11], k[10], k[9]}
        //
        // unsigned高位补0：
        //
        // {0, 0, k[9]}
        //
        // 实际只会出现：
        // 000 -> 0
        // 001 -> +x
        //
        // pd[132:111]
        // ========================================================

        case ({1'b0, 1'b0, k[9]})

            3'b000: begin
                pd[132:111] = {1'b1, 1'b1, 20'b0};
                neg[5]      = 1'b0;
            end

            3'b001: begin
                pd[132:111] = {1'b1, ~x1[20], x1[19:0]};
                neg[5]      = 1'b0;
            end

            3'b010: begin
                pd[132:111] = {1'b1, ~x1[20], x1[19:0]};
                neg[5]      = 1'b0;
            end

            3'b011: begin
                pd[132:111] = {1'b1, ~x2[20], x2[19:0]};
                neg[5]      = 1'b0;
            end

            3'b100: begin
                pd[132:111] = {1'b1, ~xn2[20], xn2[19:0]};
                neg[5]      = 1'b1;
            end

            3'b101,
            3'b110: begin
                pd[132:111] = {1'b1, ~xn1[20], xn1[19:0]};
                neg[5]      = 1'b1;
            end

            3'b111: begin
                pd[132:111] = {1'b1, 1'b1, 20'b0};
                neg[5]      = 1'b0;
            end

            default: begin
                pd[132:111] = 22'b0;
                neg[5]      = 1'b0;
            end

        endcase

    end

endmodule
